import assert from "node:assert/strict";
import fs from "node:fs/promises";
import os from "node:os";
import path from "node:path";
import { buildStoreSeo, selectPublicBeats } from "./build-store-seo.mjs";

const temp = await fs.mkdtemp(path.join(os.tmpdir(), "hiddenroom-store-seo-"));
const input = path.join(temp, "snapshot.json");
const output = path.join(temp, "output");
const outputRepeat = path.join(temp, "output-repeat");
const outputBeta = path.join(temp, "output-beta");
const publicBeat = { slug: "Ácido / Nocturno", name: "Ácido Nocturno", description: "Descripción pública", producer: "Productor público", genre: "Trap", bpm: 130, key: "Fm", price: 499, currency: "MXN" };
await fs.writeFile(input, JSON.stringify([publicBeat]));
assert.deepEqual(selectPublicBeats(JSON.parse(await fs.readFile(input, "utf8"))).map((beat) => beat.slug), ["acido-nocturno"]);
assert.throws(() => selectPublicBeats([{ slug: "same", name: "A" }, { slug: "SAME", name: "B" }]), /Slug duplicado/);
assert.throws(() => selectPublicBeats([{ slug: "../escape", name: "Traversal" }]), /Slug inválido/);
assert.throws(() => selectPublicBeats([{ slug: "source-record", name: "Origen", category: "beats", is_active: true }]), /snapshot sanitizado/);
await buildStoreSeo({ input, output, siteUrl: "https://hiddenroom.mx" });
await buildStoreSeo({ input, output: outputRepeat, siteUrl: "https://hiddenroom.mx" });
await buildStoreSeo({ input, output: outputBeta, siteUrl: "https://beta.hiddenroom.mx", noindex: true });
const page = await fs.readFile(path.join(output, "beats", "acido-nocturno", "index.html"), "utf8");
const pageRepeat = await fs.readFile(path.join(outputRepeat, "beats", "acido-nocturno", "index.html"), "utf8");
const index = await fs.readFile(path.join(output, "beats", "index.html"), "utf8");
const sitemap = await fs.readFile(path.join(output, "sitemap.xml"), "utf8");
const robots = await fs.readFile(path.join(output, "robots.txt"), "utf8");
const betaPage = await fs.readFile(path.join(outputBeta, "beats", "acido-nocturno", "index.html"), "utf8");
assert.match(page, /<title>Ácido Nocturno \| Hidden Room Beat Store<\/title>/); assert.match(page, /meta name="description"/); assert.match(page, /rel="canonical"/); assert.match(page, /property="og:title"/); assert.match(page, /Descripción pública/); assert.match(page, /Ver licencias y comprar/); assert.doesNotMatch(page, /is_active|category|email|user_id/);
assert.equal(page, pageRepeat); assert.match(index, /href="\/beats\/acido-nocturno\/"/); await fs.access(path.join(output, "beats", "acido-nocturno", "index.html"));
assert.match(sitemap, /https:\/\/hiddenroom\.mx\/beats\/acido-nocturno\//); assert.doesNotMatch(sitemap, /inactivo|privado/); assert.match(robots, /Sitemap: https:\/\/hiddenroom\.mx\/sitemap\.xml/);
assert.match(betaPage, /<meta name="robots" content="noindex, follow">/); assert.match(await fs.readFile(path.join(outputBeta, "sitemap.xml"), "utf8"), /https:\/\/beta\.hiddenroom\.mx\/beats\/acido-nocturno\//); assert.doesNotMatch(await fs.readFile(path.join(outputBeta, "sitemap.xml"), "utf8"), /https:\/\/hiddenroom\.mx\//);
console.log("build-store-seo: PASS");
